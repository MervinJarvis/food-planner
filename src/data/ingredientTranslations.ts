export function isAppLanguage(value: string | null): value is AppLanguage {
  return value === 'en' || value === 'ta' || value === 'kn' || value === 'hi';
}

export function getIngredientName(id: string, language: AppLanguage): string {
  const englishName = INGREDIENT_BY_ID[id]?.name ?? id;
  if (language === 'en') return englishName;
  const translatedNames = ingredientNames[id];
  return translatedNames?.[languageIndex[language]] || englishName;
}

export function getIngredientSearchNames(id: string, language: AppLanguage): string[] {
  const englishName = INGREDIENT_BY_ID[id]?.name ?? id;
  const localizedName = getIngredientName(id, language);
  return localizedName === englishName ? [englishName] : [localizedName, englishName];
}

export function getCategoryName(id: IngredientCategory, language: AppLanguage): string {
  if (language === 'en') {
    return CATEGORIES.find((category) => category.id === id)?.label ?? id;
  }
  return categoryNames[id][languageIndex[language]];
}
